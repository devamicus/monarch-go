package main

import (
	"bytes"
	"crypto/ed25519"
	"encoding/base64"
	"encoding/json"
	"fmt"
	"go/format"
	"io"
	"net/http"
	"os"
	"path/filepath"
	"slices"
	"strings"
	"time"
	"unicode"
)

type sealOpts struct {
	Server string
	Tag    string
	Dir    string
	Init   bool
	HTTP   *http.Client
}

type publishedKey struct {
	Kid       string `json:"kid"`
	PublicKey string `json:"public_key"`
}

const defaultPinDir = "internal/monarchpin"

func executeSeal(opts sealOpts) error {
	if opts.Dir == "" {
		opts.Dir = defaultPinDir
	}
	if opts.Tag == "" && !opts.Init {
		return fmt.Errorf("monarch: -tag is required, or pass -init to write the development pin")
	}
	if opts.Tag != "" && opts.Server == "" {
		return fmt.Errorf("monarch: -server is required")
	}
	if opts.Tag != "" {
		if err := validTag(opts.Tag); err != nil {
			return err
		}
	}
	pkg := filepath.Base(opts.Dir)
	if !validIdent(pkg) {
		return fmt.Errorf("monarch: %s is not a Go package name", pkg)
	}
	if err := os.MkdirAll(opts.Dir, 0o755); err != nil {
		return err
	}
	if opts.Tag != "" {
		keys, err := fetchKeys(opts)
		if err != nil {
			return err
		}
		body, err := renderPin(pkg, opts.Tag, keys, true)
		if err != nil {
			return err
		}
		if err := os.WriteFile(filepath.Join(opts.Dir, "pin_"+opts.Tag+".go"), body, 0o644); err != nil {
			return err
		}
		if err := saveCatalog(opts.Dir, opts.Tag, keys); err != nil {
			return err
		}
	}
	tags, err := pinTags(opts.Dir)
	if err != nil {
		return err
	}
	keys, err := developmentKeys(opts.Dir, tags)
	if err != nil {
		return err
	}
	body, err := renderPin(pkg, strings.Join(negate(tags), " && "), keys, false)
	if err != nil {
		return err
	}
	return os.WriteFile(filepath.Join(opts.Dir, "unsealed.go"), body, 0o644)
}

func fetchKeys(opts sealOpts) ([]publishedKey, error) {
	client := opts.HTTP
	if client == nil {
		client = &http.Client{Timeout: 15 * time.Second}
	}
	url := strings.TrimRight(opts.Server, "/") + "/v1/master-keys"
	res, err := client.Get(url)
	if err != nil {
		return nil, err
	}
	defer res.Body.Close()
	raw, err := io.ReadAll(io.LimitReader(res.Body, 1<<20))
	if err != nil {
		return nil, err
	}
	if res.StatusCode != http.StatusOK {
		return nil, fmt.Errorf("monarch: %s: %s", res.Status, bytes.TrimSpace(raw))
	}
	var body struct {
		Keys []publishedKey `json:"keys"`
	}
	if err := json.Unmarshal(raw, &body); err != nil {
		return nil, fmt.Errorf("monarch: master keys: %w", err)
	}
	if len(body.Keys) == 0 {
		return nil, fmt.Errorf("monarch: master keys: empty")
	}
	seen := map[string]struct{}{}
	for _, key := range body.Keys {
		if key.Kid == "" {
			return nil, fmt.Errorf("monarch: master keys: missing kid")
		}
		if _, ok := seen[key.Kid]; ok {
			return nil, fmt.Errorf("monarch: master keys: duplicate %s", key.Kid)
		}
		seen[key.Kid] = struct{}{}
		pub, err := base64.RawURLEncoding.DecodeString(key.PublicKey)
		if err != nil || len(pub) != ed25519.PublicKeySize {
			return nil, fmt.Errorf("monarch: master public key %s", key.Kid)
		}
	}
	slices.SortFunc(body.Keys, func(a, b publishedKey) int { return strings.Compare(a.Kid, b.Kid) })
	return body.Keys, nil
}

func renderPin(pkg, constraint string, keys []publishedKey, sealed bool) ([]byte, error) {
	var b strings.Builder
	b.WriteString("// Code generated by monarch seal. DO NOT EDIT.\n\n")
	if constraint != "" {
		fmt.Fprintf(&b, "//go:build %s\n\n", constraint)
	}
	fmt.Fprintf(&b, "package %s\n\n", pkg)
	if len(keys) > 0 {
		b.WriteString("import (\n\t\"crypto/ed25519\"\n\n\t\"github.com/devamicus/monarch-go/token\"\n)\n\n")
		b.WriteString("func Masters() token.Masters {\n\treturn token.Masters{\n")
		for _, key := range keys {
			pub, _ := base64.RawURLEncoding.DecodeString(key.PublicKey)
			fmt.Fprintf(&b, "\t\t%q: ed25519.PublicKey{\n", key.Kid)
			for i, part := range pub {
				if i%8 == 0 {
					b.WriteString("\t\t\t")
				}
				fmt.Fprintf(&b, "0x%02x,", part)
				if i%8 == 7 || i == len(pub)-1 {
					b.WriteString("\n")
				} else {
					b.WriteString(" ")
				}
			}
			b.WriteString("\t\t},\n")
		}
		b.WriteString("\t}\n}\n\n")
	} else {
		b.WriteString("import \"github.com/devamicus/monarch-go/token\"\n\n")
		b.WriteString("func Masters() token.Masters { return nil }\n\n")
	}
	if sealed {
		b.WriteString("func Sealed() bool { return true }\n")
	} else {
		b.WriteString("func Sealed() bool { return false }\n")
	}
	return format.Source([]byte(b.String()))
}

func saveCatalog(dir, tag string, keys []publishedKey) error {
	catalog, err := readCatalog(dir)
	if err != nil {
		return err
	}
	catalog[tag] = keys
	raw, err := json.MarshalIndent(catalog, "", "  ")
	if err != nil {
		return err
	}
	raw = append(raw, '\n')
	return os.WriteFile(filepath.Join(dir, "catalog.json"), raw, 0o644)
}

func developmentKeys(dir string, tags []string) ([]publishedKey, error) {
	catalog, err := readCatalog(dir)
	if err != nil {
		return nil, err
	}
	merged := map[string]string{}
	var out []publishedKey
	for _, tag := range tags {
		for _, key := range catalog[tag] {
			prev, ok := merged[key.Kid]
			if ok && prev != key.PublicKey {
				return nil, fmt.Errorf("monarch: master key %s differs between seals; test that server with go run -tags %s", key.Kid, tag)
			}
			if ok {
				continue
			}
			merged[key.Kid] = key.PublicKey
			out = append(out, key)
		}
	}
	slices.SortFunc(out, func(a, b publishedKey) int { return strings.Compare(a.Kid, b.Kid) })
	return out, nil
}

func readCatalog(dir string) (map[string][]publishedKey, error) {
	raw, err := os.ReadFile(filepath.Join(dir, "catalog.json"))
	if os.IsNotExist(err) {
		return map[string][]publishedKey{}, nil
	}
	if err != nil {
		return nil, err
	}
	var catalog map[string][]publishedKey
	if err := json.Unmarshal(raw, &catalog); err != nil {
		return nil, err
	}
	if catalog == nil {
		catalog = map[string][]publishedKey{}
	}
	return catalog, nil
}

func pinTags(dir string) ([]string, error) {
	entries, err := os.ReadDir(dir)
	if err != nil {
		return nil, err
	}
	var tags []string
	for _, entry := range entries {
		name := entry.Name()
		if !strings.HasPrefix(name, "pin_") || !strings.HasSuffix(name, ".go") {
			continue
		}
		tags = append(tags, strings.TrimSuffix(strings.TrimPrefix(name, "pin_"), ".go"))
	}
	slices.Sort(tags)
	return tags, nil
}

func negate(tags []string) []string {
	out := make([]string, len(tags))
	for i, tag := range tags {
		out[i] = "!" + tag
	}
	return out
}

func validTag(tag string) error {
	if !asciiIdent(tag) {
		return fmt.Errorf("monarch: tag %q is not a Go build tag", tag)
	}
	if _, banned := builtinTags[tag]; banned {
		return fmt.Errorf("monarch: tag %q is set automatically by the Go toolchain; choose a name such as prod or staging", tag)
	}
	return nil
}

func asciiIdent(name string) bool {
	if name == "" {
		return false
	}
	for i := 0; i < len(name); i++ {
		c := name[i]
		switch {
		case c >= 'a' && c <= 'z', c >= 'A' && c <= 'Z', c == '_':
		case i > 0 && c >= '0' && c <= '9':
		default:
			return false
		}
	}
	return true
}

func validIdent(name string) bool {
	if name == "" {
		return false
	}
	for i, r := range name {
		if r == '_' || unicode.IsLetter(r) {
			continue
		}
		if i > 0 && unicode.IsDigit(r) {
			continue
		}
		return false
	}
	return true
}

var builtinTags = map[string]struct{}{
	"aix": {}, "android": {}, "darwin": {}, "dragonfly": {}, "freebsd": {}, "hurd": {}, "illumos": {}, "ios": {}, "js": {}, "linux": {}, "netbsd": {}, "openbsd": {}, "plan9": {}, "solaris": {}, "wasip1": {}, "windows": {}, "zos": {},
	"386": {}, "amd64": {}, "arm": {}, "arm64": {}, "loong64": {}, "mips": {}, "mips64": {}, "mips64le": {}, "mipsle": {}, "ppc64": {}, "ppc64le": {}, "riscv64": {}, "s390x": {}, "wasm": {},
	"unix": {}, "cgo": {}, "gc": {}, "gccgo": {}, "ignore": {},
}
